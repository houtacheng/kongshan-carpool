import type { Language, TranslationDictionary } from './types';

export function getLocalizedArea(area: string, lang: Language): string {
  if (lang === 'en') {
    if (area.includes('全美東') || area.includes('全美东') || area.toLowerCase().includes('all')) return 'All East Coast';
    if (area.includes('法拉盛') || area.includes('Flushing')) return 'Flushing, NY';
    if (area.includes('曼哈頓') || area.includes('曼哈顿') || area.includes('Chinatown')) return 'Chinatown, NY';
    if (area.includes('布魯克林') || area.includes('布鲁克林') || area.includes('Brooklyn')) return 'Brooklyn, NY';
    if (area.includes('長島') || area.includes('长岛') || area.includes('Long Island')) return 'Long Island, NY';
    if (area.includes('新澤西') || area.includes('新泽西') || area.includes('Fort Lee') || area.includes('Edison')) return 'Fort Lee / Edison, NJ';
    if (area.includes('威徹斯特') || area.includes('威彻斯特') || area.includes('Westchester')) return 'Westchester, NY';
    if (area.includes('康州') || area.includes('Connecticut')) return 'Connecticut, CT';
    return area;
  }
  if (lang === 'zh-CN') {
    if (area.includes('全美東') || area.includes('全美东')) return '全美东区域';
    if (area.includes('法拉盛')) return '法拉盛 Flushing (NY)';
    if (area.includes('曼哈頓') || area.includes('曼哈顿')) return '曼哈顿华埠 Chinatown (NY)';
    if (area.includes('布魯克林') || area.includes('布鲁克林')) return '布鲁克林 Brooklyn (NY)';
    if (area.includes('長島') || area.includes('长岛')) return '长岛 Long Island (NY)';
    if (area.includes('新澤西') || area.includes('新泽西')) return '新泽西 Fort Lee / Edison (NJ)';
    if (area.includes('威徹斯特') || area.includes('威彻斯特')) return '威彻斯特 Westchester (NY)';
    if (area.includes('康州')) return '康州 Connecticut (CT)';
    return area;
  }
  // zh-TW default
  if (area.includes('全美東') || area.includes('全美东')) return '全美東區域';
  if (area.includes('法拉盛')) return '法拉盛 Flushing (NY)';
  if (area.includes('曼哈頓') || area.includes('曼哈顿')) return '曼哈頓華埠 Chinatown (NY)';
  if (area.includes('布魯克林') || area.includes('布鲁克林')) return '布魯克林 Brooklyn (NY)';
  if (area.includes('長島') || area.includes('长岛')) return '長島 Long Island (NY)';
  if (area.includes('新澤西') || area.includes('新泽西')) return '新澤西 Fort Lee / Edison (NJ)';
  if (area.includes('威徹斯特') || area.includes('威彻斯特')) return '威徹斯特 Westchester (NY)';
  if (area.includes('康州')) return '康州 Connecticut (CT)';
  return area;
}

